function stopOtherAudio(except = null) {
  [musicPlayer, soundPlayer, voicePlayer].forEach(player => {
    if (player && player !== except) {
      player.pause();
      try { player.currentTime = 0; } catch (_) {}
    }
  });
}
function playSound(src) {
  if (!src) return;
  // Treasure reveal effects can play over the soft instrumental.
  soundPlayer.pause();
  soundPlayer.src = src;
  soundPlayer.currentTime = 0;
  soundPlayer.play().catch(() => {});
}
function playMusic(mode) {
  if (!SETTINGS.musicEnabled || !musicOn) return;
  const src = musicTracks[mode];
  if (!src) return;
  stopOtherAudio(musicPlayer);
  currentMusicMode = mode;
  musicPlayer.src = src;
  musicPlayer.loop = true;
  musicPlayer.volume = mode === "finale" ? 0.42 : 0.32;
  musicPlayer.currentTime = 0;
  musicPlayer.play().catch(() => {
    $("#music-state").textContent = "Tap music";
    musicOn = false;
    setMusicButton();
  });
}
function startMusic() {
  playMusic(currentMusicMode === "off" ? "birthday" : currentMusicMode);
}
function switchToSoftInstrumental() {
  if (musicOn) playMusic("soft");
  else currentMusicMode = "soft";
}
