function revealGift(withEffects = true) {
  const gift = GIFTS[currentGift];
  giftPhase = "revealed";
  unlocked.add(currentGift);
  updateProgress();
  $("#gift-art").classList.add("unlocked");
  $("#answer-form").classList.add("hidden");
  $("#hint-button").classList.add("hidden");
  $("#hint-text").classList.add("hidden");
  $("#gift-reveal").classList.remove("hidden");
  let funnyEmojis = $("#gift-reveal").querySelector(".funny-emojis");
  if (currentGift === 6) {
    if (!funnyEmojis) {
      funnyEmojis = document.createElement("div");
      funnyEmojis.className = "funny-emojis";
      funnyEmojis.setAttribute("aria-label", "Funny chocolate surprise");
      funnyEmojis.textContent = "😂 🍫 🤪";
      $("#gift-reveal").prepend(funnyEmojis);
    }
    funnyEmojis.classList.remove("hidden");
  } else if (funnyEmojis) {
    funnyEmojis.classList.add("hidden");
  }
  $("#answer-feedback").textContent = "";
  if (withEffects) {
    playSound(gift.sound);
    confettiBurst();
  }
}
function checkAnswer(event) {
  event.preventDefault();
  const gift = GIFTS[currentGift];
  const input = $("#answer-input");
  const feedback = $("#answer-feedback");
  if (!input || !feedback) return;
  const typed = input.value.trim();

  if ($("#answer-form").dataset.phase === "passkey" || giftPhase === "passkey") {
    if (normalize(typed) === normalize(gift.passkey)) {
      feedback.textContent = "Passkey accepted! Ab gift ka guess karo… ♡";
      feedback.className = "feedback success";
      setTimeout(beginGiftGuess, 350);
    } else {
      feedback.textContent = "Passkey match nahi hui. Jo passkey mili hai, use dobara check karo. ♡";
      feedback.className = "feedback";
      input.select();
    }
    return;
  }

  if ($("#answer-form").dataset.phase === "guess" || giftPhase === "guess") {
    const accepted = (gift.answers || []).map(normalize);
    if (typed && accepted.includes(normalize(typed))) {
      feedback.textContent = "Bilkul sahi! Tumhara surprise reveal ho raha hai… ♡";
      feedback.className = "feedback success";
      setTimeout(() => revealGift(true), 400);
    } else {
      feedback.textContent = "Guess sahi nahi hai—dobara try karo, ya No press karke surprise kholo. ♡";
      feedback.className = "feedback";
      input.select();
    }
  }
}

function confettiBurst() {
  const colors = ["#f0a8d0", "#e8c98b", "#b9a0ff", "#fff8ff"];
  for (let i = 0; i < 32; i++) {
    const piece = document.createElement("span");
    piece.className = "confetti";
    piece.textContent = i % 3 === 0 ? "✦" : "♥";
    piece.style.left = `${Math.random() * 100}%`;
    piece.style.top = `${15 + Math.random() * 25}%`;
    piece.style.color = colors[i % colors.length];
    piece.style.setProperty("--drift", `${(Math.random() - .5) * 220}px`);
    piece.style.setProperty("--fall", `${500 + Math.random() * 900}px`);
    document.body.appendChild(piece);
    setTimeout(() => piece.remove(), 1500);
  }
}
function createSparkles() {
  const field = $("#sparkle-field");
  for (let i = 0; i < 34; i++) {
    const star = document.createElement("span");
    star.className = "sparkle";
    star.textContent = i % 4 === 0 ? "✦" : "·";
    star.style.left = `${Math.random() * 100}%`;
    star.style.top = `${Math.random() * 100}%`;
    star.style.setProperty("--duration", `${2.5 + Math.random() * 4}s`);
    star.style.setProperty("--delay", `${Math.random() * 4}s`);
    star.style.setProperty("--size", `${5 + Math.random() * 10}px`);
    field.appendChild(star);
  }
}
